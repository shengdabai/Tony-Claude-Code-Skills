def test_crypto_backend_without_python_ecdsa():
    private_key = ec.generate_private_key(ec.SECP256R1())
    token = jwt.encode({"sub": "42"}, private_key, algorithm="ES256")
    assert jwt.decode(token, private_key.public_key(), algorithms=["ES256"])["sub"] == "42"
    for package in ("python-jose", "ecdsa", "rsa", "pyasn1"):
        with pytest.raises(importlib.metadata.PackageNotFoundError):
            importlib.metadata.distribution(package)


@pytest.mark.asyncio
async def test_scope_authorization_unchanged(auth):
    permitted = auth.middleware.TokenData(username="42", scopes=["user"])
    assert await auth.middleware.require_scopes(["user"])(permitted) is permitted
