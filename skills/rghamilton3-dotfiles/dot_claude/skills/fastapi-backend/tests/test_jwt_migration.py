def signed(**claims):
    return jwt.encode({"sub": "42", "exp": 4102444800, **claims}, KEY, algorithm="HS256")


@pytest.mark.parametrize("route", ["template", "middleware"])
@pytest.mark.parametrize("kind", ["access"])
def test_legacy_jose_tokens(auth, route, kind):
    # These fixtures were generated by python-jose 3.5.0, not by PyJWT.
    token = FIXTURES["tokens"][kind]
    claims = jwt.decode(token, KEY, algorithms=["HS256"])
    assert claims["type"] == kind
    response = auth.client.get(f"/{route}", headers={"Authorization": f"Bearer {token}"})
    assert response.status_code == 200
    assert response.json() == {"sub": "42"}


@pytest.mark.parametrize("source", ["security", "middleware"])
@pytest.mark.parametrize("kind", ["access", "refresh"])
def test_created_token_contract(auth, source, kind):
    module = getattr(auth, source)
    create = getattr(module, f"create_{kind}_token")
    token = create(subject="42") if source == "security" else create(data={"sub": "42"})
    claims = jwt.decode(token, KEY, algorithms=["HS256"])
    assert claims["sub"] == "42" and claims["type"] == kind
    assert isinstance(claims["exp"], int)
    if source == "security" and kind == "access":
        assert claims["scopes"] == []


