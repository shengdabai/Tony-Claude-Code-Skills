@pytest.mark.parametrize("route", ["template", "middleware"])
@pytest.mark.parametrize("algorithm", ["RS256", "ES256"])
def test_configured_asymmetric_private_key(auth, monkeypatch, route, algorithm):
    from cryptography.hazmat.primitives import serialization
    from cryptography.hazmat.primitives.asymmetric import rsa
    private_key = (
        rsa.generate_private_key(public_exponent=65537, key_size=2048)
        if algorithm == "RS256" else ec.generate_private_key(ec.SECP256R1())
    )
    # Generated in memory only; never read or write a developer key file.
    pem = private_key.private_bytes(
        serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8,
        serialization.NoEncryption(),
    ).decode()
    if route == "template":
        monkeypatch.setattr(auth.security.settings, "SECRET_KEY", pem)
        monkeypatch.setattr(auth.security.settings, "ALGORITHM", algorithm)
        token = auth.security.create_access_token("42")
    else:
        monkeypatch.setattr(auth.middleware, "SECRET_KEY", pem)
        monkeypatch.setattr(auth.middleware, "ALGORITHM", algorithm)
        token = auth.middleware.create_access_token({"sub": "42"})
    response = auth.client.get(f"/{route}", headers={"Authorization": f"Bearer {token}"})
    assert response.status_code == 200, response.text
    assert response.json() == {"sub": "42"}
    # A token from a different private key must still be rejected.
    other_key = (
        rsa.generate_private_key(public_exponent=65537, key_size=2048)
        if algorithm == "RS256" else ec.generate_private_key(ec.SECP256R1())
    )
    invalid = jwt.encode({"sub": "42"}, other_key, algorithm=algorithm)
    response = auth.client.get(f"/{route}", headers={"Authorization": f"Bearer {invalid}"})
    assert response.status_code == 401
    assert response.headers["www-authenticate"] == "Bearer"
