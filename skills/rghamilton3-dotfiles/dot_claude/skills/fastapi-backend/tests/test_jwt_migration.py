@pytest.mark.parametrize("route", ["template", "middleware"])
def test_expiration_boundary_is_rejected(auth, monkeypatch, route):
    from datetime import datetime, timezone

    class FrozenDateTime(datetime):
        @classmethod
        def now(cls, tz=None):
            return datetime(2030, 1, 1, tzinfo=timezone.utc)

    monkeypatch.setattr(jwt.api_jwt, "datetime", FrozenDateTime)
    token = signed(exp=1893456000)  # Exactly 2030-01-01T00:00:00Z.
    response = auth.client.get(f"/{route}", headers={"Authorization": f"Bearer {token}"})
    assert response.status_code == 401
    assert response.headers["www-authenticate"] == "Bearer"


